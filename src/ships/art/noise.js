// Small deterministic noise helpers for procedural canvas painting.
export function mulberry32(a) {
  return function () {
    a |= 0; a = a + 0x6D2B79F5 | 0;
    let t = Math.imul(a ^ a >>> 15, 1 | a);
    t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
    return ((t ^ t >>> 14) >>> 0) / 4294967296;
  };
}
export function hash2(x, y, s = 0) {
  let h = (Math.imul(x | 0, 374761393) + Math.imul(y | 0, 668265263) + Math.imul(s | 0, 1442695041)) | 0;
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  h ^= h >>> 16;
  return (h >>> 0) / 4294967296;
}
// periodic value noise; x,y in lattice units, px/py = period in lattice cells
export function vnoise(x, y, px, py, s = 0) {
  const ix = Math.floor(x), iy = Math.floor(y);
  const fx = x - ix, fy = y - iy;
  const ux = fx * fx * (3 - 2 * fx), uy = fy * fy * (3 - 2 * fy);
  const x0 = ((ix % px) + px) % px, x1 = (x0 + 1) % px;
  const y0 = ((iy % py) + py) % py, y1 = (y0 + 1) % py;
  const a = hash2(x0, y0, s), b = hash2(x1, y0, s), c = hash2(x0, y1, s), d = hash2(x1, y1, s);
  return a + (b - a) * ux + (c - a) * uy + (a - b - c + d) * ux * uy;
}
// tiling fbm on unit square: u,v in 0..1, fx/fy base frequency (integer -> seamless)
export function fbm(u, v, fx, fy, s = 0, oct = 4) {
  let val = 0, amp = 0.5, norm = 0;
  for (let i = 0; i < oct; i++) {
    val += amp * vnoise(u * fx, v * fy, fx, fy, s + i * 31);
    norm += amp; fx *= 2; fy *= 2; amp *= 0.5;
  }
  return val / norm;
}
export const clamp01 = x => x < 0 ? 0 : x > 1 ? 1 : x;
export const smooth = (a, b, x) => { const t = clamp01((x - a) / (b - a)); return t * t * (3 - 2 * t); };
export const lerp = (a, b, t) => a + (b - a) * t;
